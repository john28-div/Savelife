-- SAVELIFE: Pet Adoption and Intake System
-- MySQL / MariaDB schema (works with XAMPP)

CREATE DATABASE IF NOT EXISTS savelife
  CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE savelife;

-- 1. USERS (one table for both users and admin; role decides the dashboard)
CREATE TABLE users (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,          -- store hashed, never plain text
  role          ENUM('user','admin') NOT NULL DEFAULT 'user',
  wants_updates TINYINT(1) NOT NULL DEFAULT 0,  -- "Send me adoption updates" checkbox
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. ANIMALS (admin adds these; also created from approved stray reports)
CREATE TABLE animals (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  name        VARCHAR(80) NOT NULL,
  type        VARCHAR(40) NOT NULL,             -- dog, cat, etc.
  age         VARCHAR(40) NOT NULL,             -- e.g. "3 months", "2 years"
  details     TEXT,
  image       VARCHAR(255),                     -- path to uploaded picture
  status      ENUM('Available','Adopted') NOT NULL DEFAULT 'Available',
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. ADOPTION REQUESTS
CREATE TABLE adoption_requests (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  user_id        INT NOT NULL,
  animal_id      INT NOT NULL,
  applicant_name VARCHAR(100) NOT NULL,
  location       VARCHAR(150) NOT NULL,
  reason         TEXT NOT NULL,
  experience     TEXT NOT NULL,
  contact        VARCHAR(100) NOT NULL,
  status         ENUM('Pending','Approved','Declined') NOT NULL DEFAULT 'Pending',
  date_requested TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id)   REFERENCES users(id)   ON DELETE CASCADE,
  FOREIGN KEY (animal_id) REFERENCES animals(id) ON DELETE CASCADE
);

-- 4. STRAY REPORTS (the "intake" side)
CREATE TABLE stray_reports (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  user_id     INT NOT NULL,
  image       VARCHAR(255),
  location    VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  contact     VARCHAR(100) NOT NULL,
  status      ENUM('Reported','Reviewed','Rescued','Closed') NOT NULL DEFAULT 'Reported',
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 5. NOTIFICATIONS
CREATE TABLE notifications (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  user_id    INT NOT NULL,
  message    VARCHAR(255) NOT NULL,
  is_read    TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

